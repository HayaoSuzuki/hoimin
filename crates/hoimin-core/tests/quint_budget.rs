use hoimin_core::{BudgetLedger, Reservation, ReservationId, RunBudgets};
use rstest::rstest;
use serde_json::Value;
use std::fmt::Debug;

fn compare<T: Debug + PartialEq + Copy>(
    actual: T,
    expected: T,
    context: &str,
) -> Result<(), String> {
    if actual == expected {
        Ok(())
    } else {
        Err(format!(
            "{context}: actual {actual:?}, expected {expected:?}"
        ))
    }
}

fn number(value: &Value) -> u64 {
    value["#bigint"]
        .as_str()
        .expect("ITF integer")
        .parse()
        .expect("nonnegative u64")
}

fn field<'a>(state: &'a Value, name: &str) -> &'a Value {
    &state[format!("Budget::BudgetModel::{name}")]
}

fn kind(index: u64) -> hoimin_core::BudgetKind {
    [
        hoimin_core::BudgetKind::Memory,
        hoimin_core::BudgetKind::Copy,
        hoimin_core::BudgetKind::Processes,
    ][usize::try_from(index).unwrap()]
}

/// Interpret ITF state values without implementing the model's transition rules.
fn replay(trace: &str) -> Result<(), String> {
    let trace: Value = serde_json::from_str(trace).unwrap();
    let states = trace["states"].as_array().expect("ITF states");
    compare(states.len() > 1, true, "nonempty oracle")?;
    compare(
        field(&states[0], "op").as_str(),
        Some("init"),
        "initial state",
    )?;
    let mut ledger = BudgetLedger::new(RunBudgets {
        memory: 2,
        copy: 2,
        processes: 2,
    });
    for (step, state) in states.iter().enumerate() {
        let id = number(field(state, "id"));
        let result = match field(state, "op").as_str().unwrap() {
            "init" => {
                compare(step, 0, "initializer position")?;
                "init"
            }
            "reserve" => match ledger.reserve(
                kind(number(field(state, "kind"))),
                number(field(state, "amount")),
            ) {
                Ok(actual_id) => {
                    compare(
                        actual_id,
                        ReservationId(id),
                        &format!("step {step}, allocated ID"),
                    )?;
                    "ok"
                }
                Err(hoimin_core::ReserveError::LimitReached(_)) => "limit",
                Err(error) => return Err(format!("unexpected error: {error:?}")),
            },
            "release" => match ledger.release(ReservationId(id)) {
                Ok(()) => "ok",
                Err(hoimin_core::BudgetError::AlreadyReleased(_)) => "released",
                Err(hoimin_core::BudgetError::UnknownReservation(_)) => "unknown",
            },
            other => return Err(format!("unknown model action: {other}")),
        };
        compare(
            result,
            field(state, "result").as_str().unwrap(),
            &format!("step {step}"),
        )?;
        let active = field(state, "active")["#set"].as_array().unwrap();
        for id in 0..=number(field(state, "nextId")) {
            let expected = active
                .iter()
                .find(|row| number(&row["id"]) == id)
                .map(|row| Reservation {
                    kind: kind(number(&row["kind"])),
                    amount: number(&row["amount"]),
                });
            compare(
                ledger.reservation(ReservationId(id)),
                expected.as_ref(),
                &format!("step {step}, ID {id}"),
            )?;
        }
        for k in 0..3 {
            let expected: u64 = active
                .iter()
                .filter(|row| number(&row["kind"]) == k)
                .map(|row| number(&row["amount"]))
                .sum();
            compare(
                ledger.reserved(kind(k)),
                expected,
                &format!("step {step}, kind {k}"),
            )?;
        }
    }
    Ok(())
}

#[rstest]
#[case::trace_0(include_str!("../../../formal/quint/traces/trace_0.itf.json"))]
#[case::trace_1(include_str!("../../../formal/quint/traces/trace_1.itf.json"))]
#[case::trace_2(include_str!("../../../formal/quint/traces/trace_2.itf.json"))]
#[case::trace_3(include_str!("../../../formal/quint/traces/trace_3.itf.json"))]
fn quint_history_matches_public_ledger(#[case] trace: &str) {
    // Arrange: expected states are generated by Quint, not by this adapter.
    let oracle = trace;
    // Act: retain the first difference as evidence for this history.
    let outcome = replay(oracle);
    // Assert.
    assert_eq!(outcome, Ok(()));
}

#[rstest]
#[case::wrong_result("/states/1/Budget::BudgetModel::result", serde_json::json!("impossible"))]
#[case::wrong_reservation_amount("/states/3/Budget::BudgetModel::active/#set/0/amount", serde_json::json!({"#bigint": "99"}))]
fn quint_adapter_rejects_incorrect_expectation(#[case] pointer: &str, #[case] value: Value) {
    // Arrange: corrupt one expected result/state in a real generated history.
    let mut oracle: Value = serde_json::from_str(include_str!(
        "../../../formal/quint/traces/trace_0.itf.json"
    ))
    .unwrap();
    *oracle.pointer_mut(pointer).unwrap() = value;
    let encoded = serde_json::to_string(&oracle).unwrap();
    // Act.
    let outcome = replay(&encoded);
    // Assert.
    assert!(outcome.is_err());
}
